"""Field layouts ("sites") for Paddy Twin: the generated grid, or a GeoJSON site file in app/sites/.

A site file is a GeoJSON FeatureCollection in WGS84 (lon, lat) with one feature per object; the kind is in
properties["kind"]:
  field     Polygon     properties: id (any), tubewell (id of its tubewell; optional, else nearest)
                      any other property is a plot attribute (e.g. soil, smartphone, consent) for the
                      logger placement planner (app/planner.py); consent = "no" excludes the plot
  logger    Point       properties: id; field (optional, else the field that contains the point)
  tubewell  Point       properties: id, name (optional)
  channel   LineString  properties: tubewell (the tubewell it carries water from)
  road      LineString  properties: width_m (optional, default 4)
Collection properties: name, label, surveyed (true only for surveyed plots), source (free text).
scripts/site_from_survey.py builds one from a GPS survey (GeoJSON or KML polygons, CSV points).

Every layout is returned in local metres around the site centre (x east, z south), so the front end can draw
it in 2D and 3D without a map projection.
"""

import json
import math
import pathlib

SITES_DIR = pathlib.Path(__file__).with_name("sites")
EARTH_R = 6_371_000.0

# generated grid (metres): 30 m fields with 2.4 m bunds, two rows per tubewell along a channel
G_FIELD, G_BUND, G_CHANNEL, G_ROAD, G_COLS, G_AREA = 30.0, 2.4, 7.2, 15.0, 12, 24


def polygon_area(poly):
    return abs(sum(x0 * z1 - x1 * z0 for (x0, z0), (x1, z1) in zip(poly, poly[1:] + poly[:1]))) / 2


def centroid(poly):
    a = cx = cz = 0.0
    for (x0, z0), (x1, z1) in zip(poly, poly[1:] + poly[:1]):
        cr = x0 * z1 - x1 * z0
        a += cr
        cx += (x0 + x1) * cr
        cz += (z0 + z1) * cr
    if abs(a) < 1e-9:
        return [sum(p[0] for p in poly) / len(poly), sum(p[1] for p in poly) / len(poly)]
    return [cx / (3 * a), cz / (3 * a)]


def point_in_polygon(x, z, poly):
    inside = False
    for (x0, z0), (x1, z1) in zip(poly, poly[1:] + poly[:1]):
        if (z0 > z) != (z1 > z) and x < x0 + (z - z0) * (x1 - x0) / (z1 - z0):
            inside = not inside
    return inside


def grid_layout(n):
    """The generated village: n fields (a multiple of 12), 24 per tubewell command area."""
    P = G_FIELD + G_BUND
    area_depth = 2 * P + G_CHANNEL + G_ROAD
    rows = n // G_COLS
    areas = math.ceil(rows / (G_AREA // G_COLS))
    fields = []
    for f in range(n):
        row, c = divmod(f, G_COLS)
        a, rr = divmod(row, G_AREA // G_COLS)
        x, z = c * P, a * area_depth + (P / 2 if rr == 0 else P + G_CHANNEL + P / 2)
        poly = [[x - P / 2, z - P / 2], [x + P / 2, z - P / 2], [x + P / 2, z + P / 2], [x - P / 2, z + P / 2]]
        fields.append({"id": str(f + 1), "poly": poly, "c": [x, z], "area_m2": G_FIELD * G_FIELD, "tw": a})
    x_end = G_COLS * P - P / 2
    tubewells, channels, roads = [], [], []
    for a in range(areas):
        zc = a * area_depth + P + G_CHANNEL / 2
        tubewells.append({"id": str(a + 1), "name": f"Tubewell {a + 1}", "x": -P / 2 - 15, "z": zc})
        channels.append({"tw": a, "pts": [[-P / 2 - 10, zc], [x_end, zc]], "width": G_CHANNEL})
        if a < areas - 1:
            zr = a * area_depth + 2 * P + G_CHANNEL + G_ROAD / 2
            roads.append({"pts": [[-P / 2 - 40, zr], [x_end + 10, zr]], "width": G_ROAD - 3.6})
    depth = areas * area_depth - G_ROAD
    roads.append({"pts": [[-P / 2 - 31.5, -20], [-P / 2 - 31.5, depth + 20]], "width": 18})
    return {"name": "grid", "label": "Generated grid", "surveyed": False, "source": "generated by Paddy Twin",
            "fields": fields, "tubewells": tubewells, "channels": channels, "roads": roads, "loggers": []}


def _features(path):
    gj = json.loads(pathlib.Path(path).read_text())
    if gj.get("type") != "FeatureCollection":
        raise ValueError(f"{path}: not a GeoJSON FeatureCollection")
    return gj.get("properties", {}), gj["features"]


def list_sites():
    out = [{"name": "grid", "label": "Generated grid", "surveyed": False, "n_fields": None, "n_loggers": 0}]
    for p in sorted(SITES_DIR.glob("*.geojson")):
        try:
            meta, feats = _features(p)
        except (ValueError, json.JSONDecodeError):
            continue
        kinds = [f.get("properties", {}).get("kind") for f in feats]
        out.append({"name": p.stem, "label": meta.get("label", p.stem), "surveyed": bool(meta.get("surveyed", False)),
                    "n_fields": kinds.count("field"), "n_loggers": kinds.count("logger")})
    return out


def load_site(name):
    """A site file as a layout in local metres. Raises KeyError for an unknown site, ValueError for a bad one."""
    path = SITES_DIR / f"{name}.geojson"
    if not path.is_file() or path.parent != SITES_DIR:
        raise KeyError(f"unknown site {name!r}")
    meta, feats = _features(path)
    by_kind = {}
    for f in feats:
        by_kind.setdefault(f.get("properties", {}).get("kind"), []).append(f)
    raw_fields = [f for f in by_kind.get("field", []) if f["geometry"]["type"] == "Polygon"]
    if not 2 <= len(raw_fields) <= 400:
        raise ValueError(f"{name}: needs 2-400 field polygons, found {len(raw_fields)}")
    lon0 = sum(c[0] for f in raw_fields for c in f["geometry"]["coordinates"][0]) / sum(len(f["geometry"]["coordinates"][0]) for f in raw_fields)
    lat0 = sum(c[1] for f in raw_fields for c in f["geometry"]["coordinates"][0]) / sum(len(f["geometry"]["coordinates"][0]) for f in raw_fields)
    kx = math.radians(1) * EARTH_R * math.cos(math.radians(lat0))
    kz = math.radians(1) * EARTH_R

    def xz(c):  # lon/lat -> metres east, metres south
        return [round((c[0] - lon0) * kx, 2), round(-(c[1] - lat0) * kz, 2)]

    tubewells = [{"id": str(f["properties"].get("id", i + 1)), "name": f["properties"].get("name") or f"Tubewell {f['properties'].get('id', i + 1)}",
                  **dict(zip("xz", xz(f["geometry"]["coordinates"])))} for i, f in enumerate(by_kind.get("tubewell", []))]
    tw_index = {t["id"]: i for i, t in enumerate(tubewells)}
    fields = []
    for i, f in enumerate(raw_fields):
        ring = [xz(c) for c in f["geometry"]["coordinates"][0]]
        if ring[0] == ring[-1]:
            ring = ring[:-1]
        if len(ring) < 3 or polygon_area(ring) < 20:
            raise ValueError(f"{name}: field {f['properties'].get('id', i + 1)} is not a valid polygon")
        c = centroid(ring)
        tw = f["properties"].get("tubewell")
        if tw is not None and str(tw) in tw_index:
            t = tw_index[str(tw)]
        elif tubewells:
            t = min(range(len(tubewells)), key=lambda k: (tubewells[k]["x"] - c[0]) ** 2 + (tubewells[k]["z"] - c[1]) ** 2)
        else:
            t = 0
        attrs = {k: v for k, v in f["properties"].items() if k not in ("kind", "id", "tubewell") and isinstance(v, (str, int, float, bool))}
        fields.append({"id": str(f["properties"].get("id", i + 1)), "poly": ring, "c": c,
                       "area_m2": round(polygon_area(ring), 1), "tw": t, "attrs": attrs})
    if not tubewells:  # no pump recorded: one notional tubewell west of the fields
        xs = [p[0] for fl in fields for p in fl["poly"]]
        zs = [p[1] for fl in fields for p in fl["poly"]]
        tubewells = [{"id": "1", "name": "Tubewell (position not surveyed)", "x": min(xs) - 15, "z": (min(zs) + max(zs)) / 2}]
    # field order: by tubewell, then west to east within rows, so the simulator's neighbour pairs are close
    fields.sort(key=lambda fl: (fl["tw"], round(fl["c"][1] / 40), fl["c"][0]))
    fid = {fl["id"]: k for k, fl in enumerate(fields)}
    loggers = []
    for i, f in enumerate(by_kind.get("logger", [])):
        x, z = xz(f["geometry"]["coordinates"])
        k = fid.get(str(f["properties"].get("field")))
        if k is None:
            k = next((j for j, fl in enumerate(fields) if point_in_polygon(x, z, fl["poly"])), None)
        if k is None:
            raise ValueError(f"{name}: logger {f['properties'].get('id', i + 1)} is not inside any field")
        loggers.append({"id": str(f["properties"].get("id", i + 1)), "field": k, "x": x, "z": z})
    channels = [{"tw": tw_index.get(str(f["properties"].get("tubewell")), 0), "pts": [xz(c) for c in f["geometry"]["coordinates"]],
                 "width": float(f["properties"].get("width_m", 2.5))}
                for f in by_kind.get("channel", []) if f["geometry"]["type"] == "LineString"]
    roads = [{"pts": [xz(c) for c in f["geometry"]["coordinates"]], "width": float(f["properties"].get("width_m", 4))}
             for f in by_kind.get("road", []) if f["geometry"]["type"] == "LineString"]
    img = imagery(name)       # the image is centred on the site's own origin (lon0, lat0)
    if img and meta.get("surveyed"):
        img["matches_plots"] = True
    return {"name": name, "label": meta.get("label", name), "surveyed": bool(meta.get("surveyed", False)),
            "source": meta.get("source", ""), "origin_lonlat": [lon0, lat0], "fields": fields, "tubewells": tubewells,
            "channels": channels, "roads": roads, "loggers": loggers, "imagery": img}


IMAGERY_DIR = SITES_DIR / "imagery"


def imagery(key, center_xz=(0.0, 0.0)):
    """Real Sentinel-2 images of a site (scripts/fetch_site_imagery.py), or None: their dates, size in metres,
    the URL folder, and where their centre lies in the layout's metres."""
    meta_path = IMAGERY_DIR / key / "meta.json"
    if not meta_path.is_file():
        return None
    meta = json.loads(meta_path.read_text())
    if not meta.get("dates"):
        return None
    return {"dates": meta["dates"], "half_size_m": meta["half_size_m"], "base": f"/imagery/{key}/",
            "center_xz": [round(float(center_xz[0]), 2), round(float(center_xz[1]), 2)],
            "attribution": meta.get("attribution", ""), "source": meta.get("source", ""),
            "matches_plots": False}


def layout(site, n_grid):
    if site == "grid":
        lay = grid_layout(n_grid)
        xs = [p[0] for f in lay["fields"] for p in f["poly"]]
        zs = [p[1] for f in lay["fields"] for p in f["poly"]]
        # the generated grid has no place: the study area's image is centred under it, as a backdrop
        lay["imagery"] = imagery("_study_area", ((min(xs) + max(xs)) / 2, (min(zs) + max(zs)) / 2))
        return lay
    return load_site(site)
